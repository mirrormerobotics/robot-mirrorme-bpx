#!/usr/bin/env python3
"""Generate the deployment URDF while preserving the pinned vendor model."""

from __future__ import annotations

import argparse
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
VENDOR_URDF = ROOT / "description/bpx/urdf/bpx.urdf"
DEPLOYMENT_URDF = ROOT / "urdf/mirrorme_bpx.urdf"


def render(source: str) -> str:
    xml_decl = '<?xml version="1.0"?>'
    robot_open = '<robot name="bpx">'
    torso_open = '  <link name="torso">'

    for token in (xml_decl, robot_open, torso_open):
        if source.count(token) != 1:
            raise ValueError(f"vendor URDF must contain exactly one {token!r}")

    generated = source.replace(
        xml_decl,
        xml_decl
        + "\n<!-- Generated from description/bpx/urdf/bpx.urdf. "
        + "Do not edit this file directly. -->",
        1,
    )
    generated = generated.replace(robot_open, '<robot name="mirrorme_bpx">', 1)
    generated = generated.replace("../meshes/", "../description/bpx/meshes/")
    generated = generated.replace(
        torso_open,
        """  <!-- Robonix-facing naming layer. The vendor torso frame is the
       physical body reference; no unmeasured geometric offset is introduced. -->
  <link name="base_link" />
  <joint name="base_link_to_torso" type="fixed">
    <parent link="base_link" />
    <child link="torso" />
    <origin xyz="0 0 0" rpy="0 0 0" />
  </joint>
  <link name="torso">""",
        1,
    )
    return generated


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed deployment URDF is not current",
    )
    args = parser.parse_args()

    expected = render(VENDOR_URDF.read_text(encoding="utf-8"))
    if args.check:
        if not DEPLOYMENT_URDF.is_file():
            print(f"missing generated URDF: {DEPLOYMENT_URDF}", file=sys.stderr)
            return 1
        if DEPLOYMENT_URDF.read_text(encoding="utf-8") != expected:
            print(
                "deployment URDF is stale; run scripts/generate_deployment_urdf.py",
                file=sys.stderr,
            )
            return 1
        return 0

    DEPLOYMENT_URDF.parent.mkdir(parents=True, exist_ok=True)
    DEPLOYMENT_URDF.write_text(expected, encoding="utf-8")
    print(DEPLOYMENT_URDF)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
