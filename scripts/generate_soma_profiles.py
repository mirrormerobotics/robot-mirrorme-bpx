"""Generate profile-specific Soma descriptions from the shared body model."""
import argparse
import copy
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
PROFILES = {
    'no-motion': (None, [], 'Inspect the body model without a Primitive or SDK session.'),
    'sdk-read-only': ('mirrorme_bpx_state', ['odom'], 'Read hardware odometry; no motion command interface.'),
    'replay-state': ('mirrorme_bpx_replay', ['odom'], 'Replay recorded odometry without a robot or SDK session.'),
    'fake-state': ('mirrorme_bpx_quadruped', ['odom', 'twist_in'], 'Publish simulated state; motion is disabled in this profile.'),
    'motion-test': ('mirrorme_bpx_motion', ['odom', 'twist_in', 'move'], 'Unreleased hardware motion testing with explicit local arm; bounded moves and continuous velocity.'),
    'motion-test-fake': ('mirrorme_bpx_motion', ['odom', 'twist_in', 'move'], 'Simulated motion testing without hardware; explicit local arm required.'),
    'posture-test': ('mirrorme_bpx_posture', ['odom', 'posture'], 'Hardware posture testing: explicit stand/sit only.'),
}


def render(profile):
    doc = copy.deepcopy(yaml.safe_load((ROOT / 'soma.yaml').read_text()))
    provider, capabilities, summary = PROFILES[profile]
    doc['robot']['components'][0]['exports'] = ([{
        'provider_id': provider,
        'capabilities': [{'path': 'robonix/primitive/quadruped/' + cap} for cap in capabilities],
    }] if provider else [])
    doc['description']['summary'] = summary
    doc['description']['can_do'] = ['Expose the pinned BPX body model through Soma.', summary]
    cannot = ['Map, localize, navigate autonomously, or avoid obstacles.',
              'Accept joint-level control, damping, or acrobatic gait commands.',
              'Claim measured IMU extrinsics or physical odometry accuracy.']
    if 'move' not in capabilities:
        cannot.append('Execute bounded move commands.')
    if 'twist_in' not in capabilities:
        cannot.append('Accept continuous velocity commands.')
    if 'posture' not in capabilities:
        cannot.append('Accept a remote posture RPC.')
    if profile in ('no-motion', 'sdk-read-only', 'replay-state', 'fake-state', 'motion-test-fake'):
        cannot.append('Control physical robot motion through this profile.')
    if profile == 'fake-state':
        cannot.append('Execute velocity input while allow_motion is false.')
    doc['description']['cannot_do'] = cannot
    doc['description']['notes'][0] = 'Deployment profile: ' + profile
    if profile.startswith('motion-test'):
        doc['description']['notes'].append('Local stand/sit are operator tools, not exported posture RPCs. Rotation move has no translation-distance gate.')
    return '# Generated by scripts/generate_soma_profiles.py; edit generator or soma.yaml.\n' + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for profile in PROFILES:
        path = ROOT / ('soma.' + profile + '.yaml')
        content = render(profile)
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, 'Soma profile is stale: ' + str(path) + '\n')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
